/**
 * Built-in 5x8 character font for the LCD's simulated CGROM (character
 * generator ROM) -- fixed dot patterns for standard printable ASCII
 * (0x20-0x7E). Codes 0-7 are CGRAM slots (lcd.createChar()) and are
 * intentionally NOT here -- see i2cLcdDevice.ts, which tracks those
 * separately since they're programmable at runtime by the sketch.
 *
 * Each glyph is 7 pixel rows x 5 pixel columns (row 8 is the blank
 * cursor/underline row). Authored as binary strings for readability --
 * '1' = lit pixel, left-to-right in the string matches left-to-right on
 * screen -- and parsed into 0-31 row values at module load. This is a
 * hand-drawn block font matching the real HD44780's glyph shapes
 * closely enough to be legible and correct in form; it is not a
 * byte-for-byte replica of a specific Hitachi ROM mask (A00 vs A02
 * genuinely differ on a handful of glyphs). Swap individual entries
 * here if you need exact fidelity to one -- nothing else in the
 * simulator cares how these bits were sourced.
 */

function bits(rows: string[]): number[] {
  const packed = rows.map((row) => parseInt(row, 2));
  while (packed.length < 8) packed.push(0);
  return packed;
}

